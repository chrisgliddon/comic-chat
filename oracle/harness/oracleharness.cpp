// ---------------------------------------------------------------------------
// Dump a CBalloon (Tier-3 #5/#6: balloon bbox/routeRgn/tail + spline cps)
// ---------------------------------------------------------------------------
static ojson::Value DumpBalloon(CBalloon* balloon) {
    ojson::Value v = ojson::Value::Obj();

    // Balloon bbox
    RECT bbox;
    balloon->GetBBox(&bbox);
    v.Set("bbox", DumpRECT(bbox));

    // trueBox and routeRgn (SRECT, relative to balloon origin)
    v.Set("trueBox", DumpSRECT(balloon->m_trueBox));
    v.Set("routeRgn", DumpSRECT(balloon->m_routeRgn));

    // CFormatInfo (line breaks)
    if (balloon->m_fInfo) {
        v.Set("formatInfo", DumpFormatInfo(*balloon->m_fInfo));
    }

    // Spline control points (Tier-3 #6)
    if (balloon->m_spline) {
        CSpline* sp = balloon->m_spline;
        ojson::Value spline = ojson::Value::Obj();
        spline.Set("nCps", ojson::Value::Int(sp->nCps));
        spline.Set("closed", ojson::Value::Bool(sp->closed ? true : false));

        ojson::Value cps = ojson::Value::Arr();
        for (int i = 0; i < sp->nCps; i++) {
            ojson::Value cp = ojson::Value::Obj();
            cp.Set("x", ojson::Value::Int(sp->cps[i].x));
            cp.Set("y", ojson::Value::Int(sp->cps[i].y));
            cps.Push(cp);
        }
        spline.Set("cps", cps);

        // Bezier points (computed by ComputeBezpts).
        // The bezpts array is allocated with exactly BezierCount() entries
        // (spline.cpp:175) and ComputeBezpts writes bezpts[0] then 3 per
        // cubic segment up to BezierCount() total. BezierCount = 3*KnotCount-8.
        // Reading past BezierCount() yields uninitialized memory and
        // non-deterministic dumps, so bound the loop strictly by BezierCount().
        if (sp->bezpts) {
            int knotCount = sp->KnotCount();
            int bezCount = sp->BezierCount();
            ojson::Value bez = ojson::Value::Arr();
            int nBezPts = bezCount;  // exact allocation, no overread
            for (int i = 0; i < nBezPts; i++) {
                ojson::Value bp = ojson::Value::Obj();
                bp.Set("x", ojson::Value::Int(sp->bezpts[i].x));
                bp.Set("y", ojson::Value::Int(sp->bezpts[i].y));
                bez.Push(bp);
            }
            spline.Set("bezpts", bez);
            spline.Set("bezierCount", ojson::Value::Int(bezCount));
            spline.Set("knotCount", ojson::Value::Int(knotCount));
        }

        v.Set("spline", spline);
    }

    // Tail/arrow geometry (Tier-3 #5). m_traj is NULL after layout: the app
    // only builds it at draw time (balloon.cpp:1788 calls SetBalloonTraj from
    // Draw), so a headless dump saw nothing and the tail went unpinned. Build
    // it here explicitly. SetBalloonTraj clones m_spline and runs AddArrow
    // over the clone, so the balloon's own spline - already dumped above - is
    // not disturbed; m_traj is draw-only state that Draw would rebuild anyway.
    //
    // Segments are heterogeneous: SetBalloonTraj adds the cloned CSpline, then
    // AddArrow appends the two CArc tail strokes (balloon.cpp:1527-1529);
    // CBWoodringBox instead adds four CLines. All derive from CSeg, which is
    // polymorphic, so dynamic_cast is the discriminator.
    // SetBalloonTraj is declared on CBWoodringNormal, not CBalloon, and in a
    // release build the ASSERTs inside it compile away - so m_spline/m_fInfo
    // must be checked here or a partially built balloon would deref NULL.
    // CBWoodringNormal::AddArrow also reads m_speaker->m_arrowX; the Box
    // override doesn't, so only the non-Box path requires a speaker. When a
    // balloon can't be built, say so rather than silently omitting the field.
    CBWoodringNormal* bn = dynamic_cast<CBWoodringNormal*>(balloon);
    bool isBox = dynamic_cast<CBWoodringBox*>(balloon) != NULL;
    // A box balloon has no m_spline at all: CBWoodringBox::SetBalloonTraj draws
    // four CLines straight off m_fInfo->m_bbox and never touches a spline or a
    // speaker. Requiring m_spline for every balloon skipped all 8 box balloons
    // in case 015 (they reported trajSkipped "no spline or formatInfo"), which
    // is why the traj census still showed zero line segments after BM_ACTION
    // was finally being sent. m_fInfo is the only universal requirement.
    if (!bn) {
        v.Set("trajSkipped", ojson::Value::Str("not a CBWoodringNormal"));
    } else if (!balloon->m_fInfo) {
        v.Set("trajSkipped", ojson::Value::Str("no formatInfo"));
    } else if (!isBox && !balloon->m_spline) {
        v.Set("trajSkipped", ojson::Value::Str("no spline to clone for the outline"));
    } else if (!isBox && !balloon->m_speaker) {
        v.Set("trajSkipped", ojson::Value::Str("no speaker for arrow"));
    } else {
        bn->SetBalloonTraj();
    }

    if (balloon->m_traj) {
        CTraj* traj = balloon->m_traj;
        ojson::Value tj = ojson::Value::Obj();
        tj.Set("closed", ojson::Value::Bool(traj->m_closed ? true : false));

        ojson::Value segs = ojson::Value::Arr();
        POSITION spos = traj->m_segs.GetHeadPosition();
        while (spos) {
            CSeg* seg = (CSeg*)traj->m_segs.GetNext(spos);
            ojson::Value s = ojson::Value::Obj();
            if (CArc* arc = dynamic_cast<CArc*>(seg)) {
                s.Set("type", ojson::Value::Str("arc"));
                s.Set("lo", DumpPOINT(arc->m_lo));
                s.Set("hi", DumpPOINT(arc->m_hi));
                s.Set("altitude", ojson::Value::Int(arc->m_altitude));
            } else if (CLine* line = dynamic_cast<CLine*>(seg)) {
                s.Set("type", ojson::Value::Str("line"));
                s.Set("lo", DumpPOINT(line->m_lo));
                s.Set("hi", DumpPOINT(line->m_hi));
            } else if (CSpline* sp = dynamic_cast<CSpline*>(seg)) {
                // The arrow-broken outline: AddArrow calls BreakSpline on this
                // clone, so its cps differ from the balloon's own spline. That
                // difference is the whole point of pinning it.
                s.Set("type", ojson::Value::Str("spline"));
                s.Set("nCps", ojson::Value::Int(sp->nCps));
                ojson::Value cps = ojson::Value::Arr();
                for (int i = 0; i < sp->nCps; i++) {
                    cps.Push(DumpPOINT(sp->cps[i]));
                }
                s.Set("cps", cps);
            } else {
                s.Set("type", ojson::Value::Str("unknown"));
            }
            segs.Push(s);
        }
        tj.Set("segs", segs);
        v.Set("traj", tj);
    }

    // Speaker
    if (balloon->m_speaker) {
        v.Set("speakerAvatarID", ojson::Value::Int(balloon->m_speaker->m_avatarID));
        v.Set("speakerFlip", ojson::Value::Int(balloon->m_speaker->m_flip));
    }

    // Balloon type
    v.Set("type", ojson::Value::Int(balloon->GetType()));

    return v;
}

// ---------------------------------------------------------------------------
// Dump a CPanel (Tier-3 #1-3: membership, avatar order/flip, zoom, body rects)
// ---------------------------------------------------------------------------
static ojson::Value DumpPanel(CPanel* panel) {
    ojson::Value v = ojson::Value::Obj();

    v.Set("seed", ojson::Value::Int((long)panel->m_seed));
    v.Set("hasBorder", ojson::Value::Bool(panel->m_hasBorder ? true : false));

    // Tier-3 #3: the zoom decision. zoomFactor is a local in LayoutAvatars and
    // Establishing() reads view state, so panel.cpp records both at the
    // decision site under ORACLE_HARNESS. backDropMode matters because
    // AdjustArtToCoord forces the factor to 1.0 when the backdrop is
    // BF_NOZOOM, so the factor alone doesn't explain the art placement.
    v.Set("zoomFactor", ojson::Value::Dbl(panel->m_oracleZoomFactor));
    v.Set("reduction", ojson::Value::Dbl(panel->m_oracleReduction));
    v.Set("establishing", ojson::Value::Bool(panel->m_oracleEstablishing ? true : false));
    v.Set("backDropMode", ojson::Value::Int(panel->m_backDrop.m_mode));
    v.Set("backDropID", ojson::Value::Int(panel->m_backDrop.m_backID));

    // Balloons (m_elements)
    ojson::Value balloons = ojson::Value::Arr();
    POSITION pos = panel->m_elements.GetHeadPosition();
    while (pos) {
        CPanelElement* elem = (CPanelElement*)panel->m_elements.GetNext(pos);
        if (elem->GetType() & PE_BALLOON) {
            balloons.Push(DumpBalloon((CBalloon*)elem));
        }
    }
    v.Set("balloons", balloons);

    // Bodies (m_bodies) - avatar order, flip, bbox
    ojson::Value bodies = ojson::Value::Arr();
    POSITION bpos = panel->m_bodies.GetHeadPosition();
    while (bpos) {
        CBody* body = (CBody*)panel->m_bodies.GetNext(bpos);
        ojson::Value b = ojson::Value::Obj();
        b.Set("avatarID", ojson::Value::Int(body->m_avatarID));
        b.Set("flip", ojson::Value::Int(body->m_flip));
        b.Set("requested", ojson::Value::Int(body->m_requested));
        b.Set("bbox", DumpSRECT(body->m_bbox));
        b.Set("arrowX", ojson::Value::Int(body->m_arrowX));
        b.Set("class", ojson::Value::Int(body->GetClass()));

        // The pose this panel actually drew (Tier-3 #7 for the panel path).
        //
        // This is NOT the same as the pose in avatarStates. That one comes from
        // CAvatarX after the message, by which point ResetAvatar has called
        // SetNeutral - and SetFaceNeutral/SetTorsoNeutral scan round-robin from
        // m_lastFace/m_lastTorso for the *next* neutral pose, so the avatar's
        // indices legitimately keep changing while its emotion stays
        // EM_NEUTRAL (0.0). That is why every avatarStates emotion reads {0,0}:
        // faithful, but the post-message neutral, not the pose the reader sees.
        // The emotional pose selected by GetBodyFromEmotion lives here, on the
        // panel's own CBody, and until now nothing dumped it.
        CAvatarX* bodyAv = GetAvatar(body->m_avatarID);
        if (body->GetClass() == BC_BODYDOUBLE) {
            CBodyDouble* bd = (CBodyDouble*)body;
            CAvatarComplex* ac = dynamic_cast<CAvatarComplex*>(bodyAv);
            if (bd->m_faceRec && ac && ac->fRec) {
                b.Set("faceIndex", ojson::Value::Int((long)(bd->m_faceRec - ac->fRec)));
                b.Set("faceEmotion", DumpEmotionPair(bd->m_faceRec->emotion, bd->m_faceRec->intensity));
                b.Set("facePoseID", ojson::Value::Int(bd->m_faceRec->poseID));
            }
            if (bd->m_torsoRec && ac && ac->bRec) {
                b.Set("torsoIndex", ojson::Value::Int((long)(bd->m_torsoRec - ac->bRec)));
                b.Set("torsoEmotion", DumpEmotionPair(bd->m_torsoRec->emotion, bd->m_torsoRec->intensity));
                b.Set("torsoPoseID", ojson::Value::Int(bd->m_torsoRec->poseID));
            }
        } else if (body->GetClass() == BC_BODYSINGLE) {
            // Simple avatars carry one record; CAvatarSimple::GetEmotions
            // reports it as the face and forces the torso to zero.
            CBodySingle* bs = (CBodySingle*)body;
            CAvatarSimple* as = dynamic_cast<CAvatarSimple*>(bodyAv);
            if (bs->m_bodyRec && as && as->bRec) {
                b.Set("bodyIndex", ojson::Value::Int((long)(bs->m_bodyRec - as->bRec)));
                b.Set("bodyEmotion", DumpEmotionPair(bs->m_bodyRec->emotion, bs->m_bodyRec->intensity));
                b.Set("bodyPoseID", ojson::Value::Int(bs->m_bodyRec->poseID));
            }
        }
        bodies.Push(b);
    }
    v.Set("bodies", bodies);

    return v;
}

// ---------------------------------------------------------------------------
// Dump a CPage (the page with its panels)
// ---------------------------------------------------------------------------
static ojson::Value DumpPage(CPage* page) {
    ojson::Value v = ojson::Value::Obj();
    v.Set("newPanel", ojson::Value::Bool(page->m_newPanel ? true : false));

    RECT bbox;
    page->GetBBox(&bbox);
    v.Set("bbox", DumpRECT(bbox));

    ojson::Value panels = ojson::Value::Arr();
    POSITION pos = page->m_panels.GetHeadPosition();
    while (pos) {
        CPanel* panel = (CPanel*)page->m_panels.GetNext(pos);
        panels.Push(DumpPanel(panel));
    }
    v.Set("panels", panels);

    return v;
}

// ---------------------------------------------------------------------------
// Dump seed ledger (Phase 0: every seed recorded)
// ---------------------------------------------------------------------------
static ojson::Value DumpSeedLedger() {
    ojson::Value v = ojson::Value::Arr();
    int n = OracleSeedRecordCount();
    for (int i = 0; i < n; i++) {
        const OracleSeedRecord* r = OracleSeedRecordAt(i);
        ojson::Value entry = ojson::Value::Obj();
        entry.Set("site", ojson::Value::Str(r->site));
        entry.Set("value", ojson::Value::Int(r->value));
        v.Push(entry);
    }
    return v;
}

// ---------------------------------------------------------------------------
// Dump avatar state (Tier-3 #7: hidden state)
// ---------------------------------------------------------------------------
static ojson::Value DumpAvatarState(USHORT avatarID) {
    ojson::Value v = ojson::Value::Obj();
    CAvatarX* av = GetAvatar(avatarID);
    if (!av) {
        v.Set("exists", ojson::Value::Bool(false));
        return v;
    }
    v.Set("exists", ojson::Value::Bool(true));
    v.Set("name", ojson::Value::Str(av->m_name ? av->m_name : ""));
    v.Set("lastDir", ojson::Value::Int(av->m_lastDir));
    v.Set("lastRight", ojson::Value::Int(av->m_lastRight));
    v.Set("lastLeft", ojson::Value::Int(av->m_lastLeft));
    v.Set("nSends", ojson::Value::Int(av->m_nSends));

    if (av->m_body) {
        ojson::Value body = ojson::Value::Obj();
        body.Set("class", ojson::Value::Int(av->m_body->GetClass()));
        body.Set("flip", ojson::Value::Int(av->m_body->m_flip));
        // NOTE: the avatar's neutral-body m_bbox is only populated by the body
        // cam's DrawBody path (RefreshBody), which the headless harness does
        // not run. Dumping it here would capture uninitialized SRECT.Top/Bottom
        // (CPanelElement ctor only sets Left/Right = -1) and break determinism.
        // The per-panel body bboxes (set by CUnitPanel::LayoutAvatars via
        // SetBBox) are dumped separately in DumpPanel and are the Tier-3 #3
        // target, so we omit the neutral bbox here.

        // Get emotion state
        CEmotion face, torso;
        av->GetEmotions(face, torso);
        ojson::Value fE = ojson::Value::Obj();
        fE.Set("emotion", ojson::Value::Dbl(face.m_emotion));
        fE.Set("intensity", ojson::Value::Dbl(face.m_intensity));
        body.Set("faceEmotion", fE);
        ojson::Value tE = ojson::Value::Obj();
        tE.Set("emotion", ojson::Value::Dbl(torso.m_emotion));
        tE.Set("intensity", ojson::Value::Dbl(torso.m_intensity));
        body.Set("torsoEmotion", tE);

        // Get indices
        CHAR chFace, chTorso;
        BYTE bbReq;
        av->GetIndices(chFace, chTorso, bbReq);
        body.Set("faceIndex", ojson::Value::Int(chFace));
        body.Set("torsoIndex", ojson::Value::Int(chTorso));
        body.Set("bbRequested", ojson::Value::Int(bbReq));

        v.Set("body", body);
    }
    return v;
}

