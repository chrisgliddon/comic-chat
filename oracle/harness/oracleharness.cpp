// Initialize the harness environment (fonts, emotion rules, avatars, DC)
// ---------------------------------------------------------------------------
static void InitHarness(const char* treeDir) {
    fprintf(stderr, "ORACLE: InitHarness start\n");
    
    // MFC requires AfxWinInit for basic functionality
    AfxWinInit(GetModuleHandle(NULL), NULL, ::GetCommandLine(), SW_HIDE);
    
    // OLE/control container init (normally in CChatApp::InitInstance)
    AfxOleInit();
    AfxEnableControlContainer();
    
    fprintf(stderr, "ORACLE: AfxWinInit + OLE init done\n");

    // Set up the global DC: desktop CClientDC with MM_TWIPS
    // (same as pageview.cpp:994-998)
    if (!cui.m_pvClientDC) {
        CClientDC* dc = new CClientDC(CWnd::FromHandle(::GetDesktopWindow()));
        dc->SetMapMode(MM_TWIPS);
        cui.m_pvClientDC = dc;
    }
    fprintf(stderr, "ORACLE: DC created\n");

    // Pin panel dimensions BEFORE SetFonts (UpdateTitleFonts depends on m_unitWidth)
    CUnitPanelPage::SetUnitPanelsPerRow(2);
    CUnitPanelPage::SetUnitPanelWidth(4860);  // pin world width
    CUnitPanelPage::SetUnitPanelHeight(4860);

    // Initialize fonts directly (replicates chat.cpp:495 + InitializeComicsFonts)
    // Pin: Comic Sans MS, 12pt -> twips
    int fontHeight = PointsToTwips(12);
    memset(&theApp.m_comicsFont, 0, sizeof(LOGFONT));
    theApp.m_comicsFont.lfHeight = fontHeight;
    theApp.m_comicsFont.lfWidth = 0;
    theApp.m_comicsFont.lfWeight = FW_NORMAL;
    theApp.m_comicsFont.lfItalic = FALSE;
    theApp.m_comicsFont.lfUnderline = FALSE;
    theApp.m_comicsFont.lfStrikeOut = FALSE;
    theApp.m_comicsFont.lfCharSet = ANSI_CHARSET;
    theApp.m_comicsFont.lfOutPrecision = OUT_DEFAULT_PRECIS;
    theApp.m_comicsFont.lfClipPrecision = CLIP_DEFAULT_PRECIS;
    theApp.m_comicsFont.lfQuality = DEFAULT_QUALITY;
    theApp.m_comicsFont.lfPitchAndFamily = DEFAULT_PITCH | FF_DONTCARE;
    strcpy(theApp.m_comicsFont.lfFaceName, "Comic Sans MS");
    theApp.m_iFontHeightBalloon = fontHeight;
    theApp.m_comicsColor = RGB(0, 0, 0);
    theApp.m_textColor = RGB(0, 0, 0);
    theApp.m_charSet = ANSI_CHARSET;
    theApp.m_bComicView = TRUE;
    theApp.m_bNoRefresh = TRUE;  // suppress view refresh calls
    theApp.m_flags1 = (DWORD)~0; // all flags on (incl F1_RTFCOMIC)
    theApp.m_bIconMembers = TRUE;
    strcpy(theApp.m_szGuiFaceName, "Comic Sans MS");

    // Create the panel fonts
    CUnitPanelPage::SetFonts(theApp.m_comicsFont, theApp.m_comicsColor);
    fprintf(stderr, "ORACLE: fonts set\n");

    // Set art directory to the tree's ComicArt folder.
    // SetArtDir (protsupp.cpp:164) constructs the avatar/backdrop dir as
    //   m_strBaseDir + "\\" + m_strDefaultArtDir
    // so m_strDefaultArtDir must be a RELATIVE name ("ComicArt"), not a full
    // path, and m_strBaseDir must be the tree root. Using a full path here
    // made SetArtDir double-join the path, so avatar loading failed for every
    // corpus case except the one using treeDir="." (which collapsed via ".").
    theApp.m_strBaseDir = treeDir;
    theApp.m_strDefaultArtDir = "ComicArt";
    // Initialize the avatar/backdrop dirs to match (SetArtDir will be called
    // again by InitMyDocument, but InitializeBackDrops below reads them).
    theApp.m_strBackDropDir = CString(treeDir) + "\\ComicArt";
    theApp.m_strAvatarDir = theApp.m_strBackDropDir;
#ifdef ORACLE_HARNESS
    fprintf(stderr, "ORACLE: treeDir=%s artDir=%s\n", treeDir, (const char*)theApp.m_strAvatarDir);
#endif

    // Initialize backdrops
    InitializeBackDrops();
    fprintf(stderr, "ORACLE: backdrops initialized\n");

    // Load emotion rules (textpose.cpp)
    LoadEmotionStrings();
    InitializeEmotionRules();
    fprintf(stderr, "ORACLE: emotion rules initialized\n");

    // Initialize avatar registry
    InitializeAvatars();
    fprintf(stderr, "ORACLE: avatars initialized\n");
}

// ---------------------------------------------------------------------------
// Load an avatar by name and return its ID.
// In the real app, GetAvatar3(avName, pui) associates each avatar with a
// CUserInfo (so EvalPair/AddTalkTos can deref av->m_userInfo->m_udi.m_talkTos).
// The harness uses LoadAvatar directly, so we must synthesize a CUserInfo per
// avatar and attach it. The userInfoList keeps the CUserInfo objects alive
// for the document's lifetime.
// ---------------------------------------------------------------------------
static CPtrList userInfoList;

static CAvatarX* LoadAvatarNoThrow(const char* name) {
#ifdef _MSC_VER
    CAvatarX* av = NULL;
    __try {
        av = LoadAvatar(name);
    } __except(EXCEPTION_EXECUTE_HANDLER) {
        av = NULL;
    }
    return av;
#else
    // No SEH on clang, so an access violation inside the loader becomes a real crash
    // instead of a NULL return. That is the honest behaviour rather than a silent
    // platform difference - and the Windows harness is where to diagnose which avatar
    // did it. Same treatment as the guards in avbdump.cpp.
    return LoadAvatar(name);
#endif
}

static USHORT LoadAvatarByName(const char* name) {
    fprintf(stderr, "ORACLE: loading avatar '%s'\n", name);
    fflush(stderr);
    CAvatarX* av = LoadAvatarNoThrow(name);
    if (!av) {
        fprintf(stderr, "ORACLE: failed to load avatar '%s'\n", name);
        return 0;
    }
    // Synthesize a CUserInfo so panel ordering (EvalPair/AddTalkTos) can
    // dereference av->m_userInfo->m_udi.m_talkTos without crashing. The talkTos
    // list stays empty (no talk-to targets), which is the correct neutral
    // state for the corpus (messages with talk-tos are a separate case).
    CUserInfo* pui = new CUserInfo();
    pui->SetAvatarID(av->m_avatarID);
    pui->SetName(name);
    av->m_userInfo = pui;
    userInfoList.AddTail(pui);
    fprintf(stderr, "ORACLE: avatar '%s' loaded as ID %d (pui=%p)\n",
            name, av->m_avatarID, (void*)pui);
    return av->m_avatarID;
}

// ---------------------------------------------------------------------------
// Main: replay inputs.json -> expected.json
// ---------------------------------------------------------------------------
int main(int argc, char** argv) {
    // Parse args
    if (argc < 2) {
        fprintf(stderr, "usage: OracleHarness.exe <inputs.json> <expected.json>\n");
        fprintf(stderr, "       OracleHarness.exe --glyphs <glyphs.json>\n");
        fprintf(stderr, "       OracleHarness.exe --codecs <codecs.json>\n");
        fprintf(stderr, "       OracleHarness.exe --ccc <ccc.json> [treeDir]\n");
        fprintf(stderr, "       OracleHarness.exe --avb <outDir> [artDir]\n");
        return 2;
    }

    // Determine tree directory (parent of the harness exe, or from inputs)
    // Default: ".." relative to CWD (CI runs from v2.5-beta-1-modern\)
    char treeDir[MAX_PATH] = "..";
    // Also try exe-relative path as fallback
    char exeDir[MAX_PATH];
    GetModuleFileName(NULL, exeDir, MAX_PATH);
    char* slash = strrchr(exeDir, '\\');
    if (slash) {
        *slash = 0;  // exeDir = Release/
        slash = strrchr(exeDir, '\\');
        if (slash) {
            *slash = 0;  // exeDir = v2.5-beta-1-modern/
            // If the directory exists, use it; otherwise keep ".."
            char testPath[MAX_PATH];
            snprintf(testPath, MAX_PATH, "%s\\ComicArt", exeDir);
            if (GetFileAttributes(testPath) != (DWORD)-1) {
                strcpy(treeDir, exeDir);
            }
        }
    }

    // Glyph capture mode
    if (strcmp(argv[1], "--glyphs") == 0) {
        if (argc < 3) {
            fprintf(stderr, "usage: OracleHarness.exe --glyphs <glyphs.json>\n");
            return 2;
        }
        AfxWinInit(GetModuleHandle(NULL), NULL, ::GetCommandLine(), SW_HIDE);
        if (!cui.m_pvClientDC) {
            CClientDC* dc = new CClientDC(CWnd::FromHandle(::GetDesktopWindow()));
            dc->SetMapMode(MM_TWIPS);
            cui.m_pvClientDC = dc;
        }
        ojson::Value glyphs = CaptureGlyphs();
        FILE* f = fopen(argv[2], "wb");
        if (!f) { fprintf(stderr, "cannot write %s\n", argv[2]); return 1; }
        std::string out = glyphs.EmitToString();
        fwrite(out.c_str(), 1, out.size(), f);
        fclose(f);
        printf("glyphs written to %s\n", argv[2]);
        return 0;
    }

    // Textpose capture mode (Tier-1 #1 dump for the TS port's golden)
    if (strcmp(argv[1], "--textpose") == 0) {
        if (argc < 3) {
            fprintf(stderr, "usage: OracleHarness.exe --textpose <textpose.json>\n");
            return 2;
        }
        AfxWinInit(GetModuleHandle(NULL), NULL, ::GetCommandLine(), SW_HIDE);
        // Textpose doesn't need a DC, but InitializeEmotionRules calls
        // LoadString which needs the resource instance (AfxWinInit handles it).
        LoadEmotionStrings();
        InitializeEmotionRules();
        ojson::Value tp = CaptureTextpose();
        FILE* f = fopen(argv[2], "wb");
        if (!f) { fprintf(stderr, "cannot write %s\n", argv[2]); return 1; }
        std::string out = tp.EmitToString();
        fwrite(out.c_str(), 1, out.size(), f);
        fclose(f);
        printf("textpose written to %s\n", argv[2]);
        return 0;
    }

    // Avatario capture mode (Tier-1 #3 dump: emotion quantization round-trip).
    // Pure-logic, no DC or avatar loading needed — just the avatario module.
    if (strcmp(argv[1], "--avatario") == 0) {
        if (argc < 3) {
            fprintf(stderr, "usage: OracleHarness.exe --avatario <avatario.json>\n");
            return 2;
        }
        AfxWinInit(GetModuleHandle(NULL), NULL, ::GetCommandLine(), SW_HIDE);
        ojson::Value av = CaptureAvatario();
        FILE* f = fopen(argv[2], "wb");
        if (!f) { fprintf(stderr, "cannot write %s\n", argv[2]); return 1; }
        std::string out = av.EmitToString();
        fwrite(out.c_str(), 1, out.size(), f);
        fclose(f);
        printf("avatario written to %s\n", argv[2]);
        return 0;
    }

    // Avatar-pose capture mode (Tier-1 #2 dump: emotion-to-pose selection on
    // synthetic avatars). No DC, no avatar loading, no chatdoc — just the
    // GetBodyFromEmotion nearest-neighbor logic exercised on known input.
    if (strcmp(argv[1], "--avatar-pose") == 0) {
        if (argc < 3) {
            fprintf(stderr, "usage: OracleHarness.exe --avatar-pose <avatar.json>\n");
            return 2;
        }
        AfxWinInit(GetModuleHandle(NULL), NULL, ::GetCommandLine(), SW_HIDE);
        ojson::Value av = CaptureAvatarPose();
        FILE* f = fopen(argv[2], "wb");
        if (!f) { fprintf(stderr, "cannot write %s\n", argv[2]); return 1; }
        std::string out = av.EmitToString();
        fwrite(out.c_str(), 1, out.size(), f);
        fclose(f);
        printf("avatar-pose written to %s\n", argv[2]);
        return 0;
    }

    // Stateless codec capture (Tier-1 #6, #7, #8, #9, #12). Needs AfxWinInit
    // for CString/CDWordArray/CStringArray, but no DC, avatars, or document.
    if (strcmp(argv[1], "--codecs") == 0) {
        if (argc < 3) {
            fprintf(stderr, "usage: OracleHarness.exe --codecs <codecs.json>\n");
            return 2;
        }
        AfxWinInit(GetModuleHandle(NULL), NULL, ::GetCommandLine(), SW_HIDE);
        ojson::Value cx = CaptureCodecs();
        FILE* f = fopen(argv[2], "wb");
        if (!f) { fprintf(stderr, "cannot write %s\n", argv[2]); return 1; }
        std::string out = cx.EmitToString();
        fwrite(out.c_str(), 1, out.size(), f);
        fclose(f);
        printf("codecs written to %s\n", argv[2]);
        return 0;
    }

    // .ccc transcript codec capture (Tier-1 #10). Needs more setup than
    // --codecs: the parse constructors want a CChatDoc for LookupPui. It is a
    // bare doc though - no InitMyDocument, since pages and panels play no part
    // in serialising a history entry.
    if (strcmp(argv[1], "--ccc") == 0) {
        if (argc < 3) {
            fprintf(stderr, "usage: OracleHarness.exe --ccc <ccc.json> [treeDir]\n");
            return 2;
        }
        char treeDir[MAX_PATH] = ".";
        if (argc >= 4) {
            strncpy(treeDir, argv[3], MAX_PATH - 1);
            treeDir[MAX_PATH - 1] = 0;
        }
        InitHarness(treeDir);
        COracleChatDoc* doc = new COracleChatDoc();
        cui.m_pvChatDoc = doc;
        doc->m_view = NULL;
        doc->m_bComicView = TRUE;
        doc->SetComicsTitle("Oracle Comic");
        fprintf(stderr, "ORACLE: ccc - bare doc ready\n"); fflush(stderr);

        ojson::Value cc = CaptureCcc(doc);
        FILE* f = fopen(argv[2], "wb");
        if (!f) { fprintf(stderr, "cannot write %s\n", argv[2]); return 1; }
        std::string out = cc.EmitToString();
        fwrite(out.c_str(), 1, out.size(), f);
        fclose(f);
        printf("ccc written to %s\n", argv[2]);
        return 0;
    }

    // Tier-2: .avb/.bgb asset manifests + decoded-pixel CRC32s. Needs less
    // setup than any other mode - avbfile.cpp and dib.cpp reference theApp only
    // for the #include, never for state, so there is no DC, no font, no emotion
    // table and no avatar registry here. Keeping it that way is the point: the
    // dump then cannot be perturbed by anything outside the two files under
    // test. Writes one manifest per asset plus an index.
    if (strcmp(argv[1], "--avb") == 0) {
        if (argc < 3) {
            fprintf(stderr, "usage: OracleHarness.exe --avb <outDir> [artDir]\n");
            return 2;
        }
        const char* outDir = argv[2];
        char artDir[MAX_PATH];
        if (argc >= 4) {
            strncpy(artDir, argv[3], MAX_PATH - 1);
            artDir[MAX_PATH - 1] = 0;
        } else {
            snprintf(artDir, MAX_PATH, "%s\\ComicArt", treeDir);
        }
        AfxWinInit(GetModuleHandle(NULL), NULL, ::GetCommandLine(), SW_HIDE);

        ojson::Value idx = CaptureAvb(artDir, outDir);
        char idxPath[MAX_PATH];
        snprintf(idxPath, MAX_PATH, "%s\\index.json", outDir);
        FILE* f = fopen(idxPath, "wb");
        if (!f) { fprintf(stderr, "cannot write %s\n", idxPath); return 1; }
        std::string out = idx.EmitToString();
        fwrite(out.c_str(), 1, out.size(), f);
        fclose(f);
        printf("avb manifests written to %s\n", outDir);
        return 0;
    }

    // Normal replay mode
    if (argc < 3) {
        fprintf(stderr, "usage: OracleHarness.exe <inputs.json> <expected.json>\n");
        return 2;
    }

    const char* inputsPath = argv[1];
    const char* expectedPath = argv[2];

    // Read inputs.json
    FILE* fin = fopen(inputsPath, "rb");
    if (!fin) { fprintf(stderr, "cannot open %s\n", inputsPath); return 1; }
    fseek(fin, 0, SEEK_END);
    long sz = ftell(fin);
    fseek(fin, 0, SEEK_SET);
    std::string inputsText(sz, '\0');
    fread(&inputsText[0], 1, sz, fin);
    fclose(fin);

    ojson::Value inputs;
    std::string parseErr;
    if (!ojson::Parse(inputsText, inputs, parseErr)) {
        fprintf(stderr, "parse error in %s: %s\n", inputsPath, parseErr.c_str());
        return 1;
    }

    // Read seed and config
    unsigned int seed = (unsigned int)inputs.GetInt("seed", 42);
    unsigned int tickBase = (unsigned int)inputs.GetInt("tickSeedBase", 1000);
    int panelsWide = (int)inputs.GetInt("panelsWide", 2);
    std::string treeDirFromInputStr = inputs.GetStr("treeDir", "");
    const char* treeDirFromInput = treeDirFromInputStr.c_str();
    if (treeDirFromInput[0]) {
        strncpy(treeDir, treeDirFromInput, MAX_PATH - 1);
        treeDir[MAX_PATH - 1] = 0;
    }

    // Initialize the harness environment
    InitHarness(treeDir);
    fprintf(stderr, "ORACLE: InitHarness complete\n");

    // Panel dimensions already set in InitHarness (before SetFonts)
    CUnitPanelPage::SetUnitPanelsPerRow(panelsWide);  // override from inputs

    // panelsWide alone only sets panels-per-row here: the real client sizes the
    // panel via CPageView::SetPanelsWide -> GetProspectivePanelWidth, which
    // needs a window. So a narrow panel was unreachable from the corpus, and
    // with it the avatar-overflow branch in LayoutAvatars (sumWidth >
    // m_unitWidth) - measured as never taken across all 267 panels. This knob
    // makes panel geometry an explicit corpus input; MINUNITPANELWIDTH (2300)
    // is the floor the real SetPanelsWide clamps to, so values below it would
    // not be reachable in the app either.
    // Width and height are separate knobs on purpose. Bodies are scaled to
    // maxBodyHeight = m_unitHeight / 1.9 (panel.cpp:755) and their widths scale
    // with that ratio, so shrinking width and height together shrinks the
    // avatars just as much and sumWidth can never overtake m_unitWidth - which
    // is why a square 2300 panel still reported reduction 1.0. A narrow *tall*
    // panel is what overflows: full-height bodies in a narrow frame.
    int panelWidth = (int)inputs.GetInt("panelWidth", 4860);
    int panelHeight = (int)inputs.GetInt("panelHeight", 4860);
    if (panelWidth < MINUNITPANELWIDTH || panelHeight < MINUNITPANELHEIGHT) {
        fprintf(stderr, "ORACLE: panel %dx%d is below the MINUNITPANEL floor %dx%d\n",
                panelWidth, panelHeight, MINUNITPANELWIDTH, MINUNITPANELHEIGHT);
        return 2;
    }
    if (panelWidth != 4860 || panelHeight != 4860) {
        CUnitPanelPage::SetUnitPanelWidth(panelWidth);
        CUnitPanelPage::SetUnitPanelHeight(panelHeight);
        fprintf(stderr, "ORACLE: panel geometry overridden to %dx%d\n", panelWidth, panelHeight);
    }

    // Activate the oracle determinism layer
    OracleSeedActivate(seed, tickBase);
    fprintf(stderr, "ORACLE: seed activated (seed=%u, tickBase=%u)\n", seed, tickBase);

    // Load avatars from the inputs
    ojson::Value* avatars = inputs.Find("avatars");
    fprintf(stderr, "ORACLE: loading avatars (avatars=%p, type=%d)\n", (void*)avatars, avatars ? avatars->type : -1);

    fprintf(stderr, "ORACLE: creating CChatDoc...\n");
    // Create the document
    COracleChatDoc* doc = new COracleChatDoc();
    fprintf(stderr, "ORACLE: CChatDoc created\n");
    cui.m_pvChatDoc = doc;  // GetChatDoc() macro will find it

    // m_view is not initialized by CChatDoc ctor — set to NULL so
    // RefreshPanelN's ORACLE_HARNESS guard skips UpdateViewsX
    doc->m_view = NULL;

    // Set comics view mode
    doc->m_bComicView = TRUE;

    // Pre-set a fixed title so GetComicsTitle() doesn't call GetRandomTitle()
    // (which needs string resources the console exe doesn't have)
    doc->SetComicsTitle("Oracle Comic");

    fprintf(stderr, "ORACLE: calling InitMyDocument...\n");
    // Initialize the document (creates first page, seeds the PRNG)
    doc->InitMyDocument();
    fprintf(stderr, "ORACLE: InitMyDocument complete\n");
    fflush(stderr);

    // Load avatars and assign to speakers
    fprintf(stderr, "ORACLE: setting up speaker map\n");
    fflush(stderr);

    // Load avatars and assign to speakers
    // inputs.avatars: array of {name, speakerId}
    // We load each avatar and map speakerId -> avatarID
    struct SpeakerAv { int speakerId; USHORT avatarID; };
    SpeakerAv speakerMap[64];
    int nSpeakers = 0;

    if (avatars && avatars->type == ojson::T_ARRAY) {
        for (size_t i = 0; i < avatars->arr.size(); i++) {
            ojson::Value& a = avatars->arr[i];
            std::string nameStr = a.GetStr("name", "");
            const char* name = nameStr.c_str();
            int speakerId = (int)a.GetInt("speakerId", (long)i);
            if (nSpeakers < 64) {
                USHORT avID = LoadAvatarByName(name);
                speakerMap[nSpeakers].speakerId = speakerId;
                speakerMap[nSpeakers].avatarID = avID;
                nSpeakers++;
            }
        }
    }

    // If no avatars specified, load a default
    if (nSpeakers == 0) {
        USHORT avID = LoadAvatarByName("bolo");
        speakerMap[0].speakerId = 1;
        speakerMap[0].avatarID = avID;
        nSpeakers = 1;
    }

    // Set my avatar to the first one
    if (nSpeakers > 0) {
        doc->m_myAvatarID = speakerMap[0].avatarID;
    }
    fprintf(stderr, "ORACLE: myAvatarID = %d, nSpeakers = %d\n", doc->m_myAvatarID, nSpeakers);
    fflush(stderr);

    // Replay messages
    ojson::Value* messages = inputs.Find("messages");
    ojson::Value dumpRoot = ojson::Value::Obj();
    ojson::Value perMessageDumps = ojson::Value::Arr();
    fprintf(stderr, "ORACLE: messages = %p, type = %d, count = %d\n", (void*)messages, messages ? messages->type : -1, messages ? (int)messages->arr.size() : 0);
    fflush(stderr);

    // Mode constants (from protsupp.h / chatprot.h)
    // BM_SAY=0, BM_WHISPER=1, BM_THINK=2, BM_ACTION=4
    // These map to the uModes parameter of ProcessLine

    if (messages && messages->type == ojson::T_ARRAY) {
        for (size_t i = 0; i < messages->arr.size(); i++) {
            ojson::Value& msg = messages->arr[i];
            int speakerId = (int)msg.GetInt("speakerId", 1);
            std::string textStr = msg.GetStr("text", "");
            const char* text = textStr.c_str();
            int mode = (int)msg.GetInt("mode", 0); // 0=say, 1=whisper, 2=think, 4=action
            int bbCooked = (int)msg.GetInt("bbCooked", 1);

            // Find avatarID for this speaker
            USHORT avatarID = 0;
            for (int s = 0; s < nSpeakers; s++) {
                if (speakerMap[s].speakerId == speakerId) {
                    avatarID = speakerMap[s].avatarID;
                    break;
                }
            }
            if (!avatarID && nSpeakers > 0) {
                avatarID = speakerMap[0].avatarID;
            }

            // Process the line through the engine
            fprintf(stderr, "ORACLE: ProcessLine(avID=%d, text='%s', mode=%d)\n", avatarID, text, mode);
            fflush(stderr);
            doc->ProcessLine(avatarID, text, (USHORT)mode, (BYTE)bbCooked, NULL);
            fprintf(stderr, "ORACLE: ProcessLine done\n");
            fflush(stderr);

            // Dump state after this message
            ojson::Value msgDump = ojson::Value::Obj();
            msgDump.Set("messageIndex", ojson::Value::Int((long)i));
            msgDump.Set("speakerId", ojson::Value::Int(speakerId));
            msgDump.Set("text", ojson::Value::Str(text));
            msgDump.Set("mode", ojson::Value::Int(mode));

            // Dump the current page (tail of m_pages is the newest; head is
            // actually the newest per AddNewPage which does AddHead... but
            // the engine's AddLine uses GetTail which is the oldest page.
            // Wait: AddNewPage does m_pages.AddHead, and AddLine uses
            // m_pages.GetTail() -- so the first page is at the tail.
            // The "current" page being written to is the tail.)
            CPage* currentPage = (CPage*)doc->m_pages.GetTail();
            if (currentPage) {
                msgDump.Set("page", DumpPage(currentPage));
            }

            // Dump all pages (for multi-panel pagination tracking)
            ojson::Value allPages = ojson::Value::Arr();
            POSITION ppos = doc->m_pages.GetHeadPosition();
            while (ppos) {
                CPage* p = (CPage*)doc->m_pages.GetNext(ppos);
                allPages.Push(DumpPage(p));
            }
            msgDump.Set("allPages", allPages);

            // Dump avatar states for all speakers
            ojson::Value avStates = ojson::Value::Obj();
            for (int s = 0; s < nSpeakers; s++) {
                char key[32];
                snprintf(key, sizeof(key), "%d", speakerMap[s].speakerId);
                avStates.Set(key, DumpAvatarState(speakerMap[s].avatarID));
            }
            msgDump.Set("avatarStates", avStates);

            perMessageDumps.Push(msgDump);
        }
    }

    dumpRoot.Set("seed", ojson::Value::Int((long)seed));
    dumpRoot.Set("tickSeedBase", ojson::Value::Int((long)tickBase));
    dumpRoot.Set("panelsWide", ojson::Value::Int(panelsWide));
    // Record the geometry the run actually used, not just what was requested -
    // every world-unit coordinate below is relative to it.
    dumpRoot.Set("panelWidth", ojson::Value::Int(CUnitPanelPage::m_unitWidth));
    dumpRoot.Set("panelHeight", ojson::Value::Int(CUnitPanelPage::m_unitHeight));
    dumpRoot.Set("messages", perMessageDumps);

    // Dump seed ledger (Phase 0 determinism verification)
    dumpRoot.Set("seedLedger", DumpSeedLedger());

    // Dump font info for this run
    ojson::Value fontInfo = ojson::Value::Obj();
    fontInfo.Set("faceName", ojson::Value::Str("Comic Sans MS"));
    fontInfo.Set("lfHeight", ojson::Value::Int(theApp.m_iFontHeightBalloon));
    fontInfo.Set("charSet", ojson::Value::Int(ANSI_CHARSET));
    dumpRoot.Set("fontConfig", fontInfo);

    // Write expected.json
    std::string out = dumpRoot.EmitToString();
    FILE* fout = fopen(expectedPath, "wb");
    if (!fout) { fprintf(stderr, "cannot write %s\n", expectedPath); return 1; }
    fwrite(out.c_str(), 1, out.size(), fout);
    fclose(fout);

    printf("oracle dump written to %s (%d messages)\n",
           expectedPath, (int)perMessageDumps.arr.size());

    // Cleanup
    delete doc;

    return 0;
}