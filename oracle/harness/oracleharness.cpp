// Escape a byte string for the dump. Control characters are the *point* of the
// formatting codec, so they must survive the round trip legibly; ojson emits
// bytes < 0x20 as \u00xx and rejects escapes above 0xFF on parse, which suits a
// byte-oriented corpus.
static ojson::Value CodecStr(const char* s) {
    return ojson::Value::Str(s ? s : "");
}

static ojson::Value DumpFormattingArray(CDWordArray& rgdw) {
    // Element layout per format.cpp:305 - HIWORD is the offset of the first
    // character, LOWORD the format word (effects | fg | bg).
    ojson::Value arr = ojson::Value::Arr();
    for (int i = 0; i < rgdw.GetSize(); i++) {
        DWORD dw = rgdw[i];
        ojson::Value e = ojson::Value::Obj();
        e.Set("raw", ojson::Value::Int((long)dw));
        e.Set("offset", ojson::Value::Int((long)HIWORD(dw)));
        e.Set("format", ojson::Value::Int((long)LOWORD(dw)));
        arr.Push(e);
    }
    return arr;
}

static ojson::Value CaptureCodecs() {
    ojson::Value root = ojson::Value::Obj();

    // --- Tier-1 #9: mode maps -------------------------------------------
    // Every byte for the index maps; the documented mode values plus the
    // combinations MakeBalloon accepts for SM2BM/BM2SM. BM2SM's argument is a
    // bit set, so the combined ACTION forms matter.
    {
        fprintf(stderr, "ORACLE: codecs - modeMaps\n"); fflush(stderr);
        ojson::Value mm = ojson::Value::Obj();
        ojson::Value i2b = ojson::Value::Arr(), b2i = ojson::Value::Arr();
        for (int i = 0; i < 256; i++) {
            i2b.Push(ojson::Value::Int((long)IndexToByte((BYTE)i)));
            b2i.Push(ojson::Value::Int((long)ByteToIndex((BYTE)i)));
        }
        mm.Set("indexToByte", i2b);
        mm.Set("byteToIndex", b2i);

        ojson::Value sm2bm = ojson::Value::Arr();
        for (int sm = 0; sm <= 8; sm++) {
            ojson::Value e = ojson::Value::Obj();
            e.Set("in", ojson::Value::Int((long)sm));
            e.Set("out", ojson::Value::Int((long)SM2BM((BYTE)sm)));
            sm2bm.Push(e);
        }
        mm.Set("sm2bm", sm2bm);

        static const USHORT kBmProbes[] = {
            0, BM_SAY, BM_WHISPER, BM_THINK, BM_ACTION,
            BM_ACTION | BM_SAY, BM_ACTION | BM_WHISPER, BM_ACTION | BM_THINK,
            BM_SOUND, BM_AWAY, BM_HERESINFO, BM_NOFORMAT, BM_EXCHAN,
            BM_SAY | BM_THINK
        };
        ojson::Value bm2sm = ojson::Value::Arr();
        for (int i = 0; i < (int)(sizeof(kBmProbes) / sizeof(kBmProbes[0])); i++) {
            ojson::Value e = ojson::Value::Obj();
            e.Set("in", ojson::Value::Int((long)kBmProbes[i]));
            e.Set("out", ojson::Value::Int((long)BM2SM(kBmProbes[i])));
            bm2sm.Push(e);
        }
        mm.Set("bm2sm", bm2sm);
        root.Set("modeMaps", mm);
    }

    // --- Tier-1 #7: formatting codec ------------------------------------
    {
        fprintf(stderr, "ORACLE: codecs - formatting\n"); fflush(stderr);
        ojson::Value fmt = ojson::Value::Obj();

        // nFillFormatting: every effect toggle in isolation, then the colour
        // paths. chFirstFormattedChar being a digit triggers the documented
        // ^k33 -> ^k0133 hack (format.cpp:502-508), so probe both sides of it.
        struct FillProbe { WORD cur; WORD next; char first; const char* note; };
        static const FillProbe kFill[] = {
            { 0,        0,          'a', "no change" },
            { 0,        wBold,      'a', "bold on" },
            { wBold,    0,          'a', "bold off" },
            { 0,        wItalic,    'a', "italic on" },
            { 0,        wUnderline, 'a', "underline on" },
            { 0,        wFixedPitch,'a', "fixed pitch on" },
            { 0,        wSymbol,    'a', "symbol on" },
            { 0,        (WORD)(wBold | wItalic | wUnderline), 'a', "three at once" },
            { 0x0033,   0,          '3', "colour off, digit follows - ^k33 hack" },
            { 0x0033,   0,          'x', "colour off, non-digit follows" },
            { 0,        0x0033,     '3', "colour on, digit follows" },
            { 0x0011,   0x0022,     'z', "colour change" }
        };
        ojson::Value fillArr = ojson::Value::Arr();
        for (int i = 0; i < (int)(sizeof(kFill) / sizeof(kFill[0])); i++) {
            char buf[128];
            memset(buf, 0, sizeof(buf));
            short n = nFillFormatting(buf, kFill[i].cur, kFill[i].next, kFill[i].first);
            ojson::Value e = ojson::Value::Obj();
            e.Set("note", ojson::Value::Str(kFill[i].note));
            e.Set("curFormat", ojson::Value::Int((long)kFill[i].cur));
            e.Set("nextFormat", ojson::Value::Int((long)kFill[i].next));
            e.Set("firstFormattedChar", ojson::Value::Int((long)(BYTE)kFill[i].first));
            e.Set("returned", ojson::Value::Int((long)n));
            e.Set("bytes", CodecStr(buf));
            ojson::Value raw = ojson::Value::Arr();
            for (short b = 0; b < n; b++) raw.Push(ojson::Value::Int((long)(BYTE)buf[b]));
            e.Set("byteValues", raw);
            fillArr.Push(e);
        }
        fmt.Set("nFillFormatting", fillArr);

        // SzControlLess: strips control codes out of the text and reports the
        // formatting runs it found. Input must be mutable.
        static const char* kLessProbes[] = {
            "plain text",
            "\x02" "bold then plain\x02 tail",
            "\x16" "italic\x16",
            "\x1F" "underline\x1F",
            "\x03" "04red text\x03",
            "mixed \x02" "bold \x16" "and italic\x16\x02 done",
            "\x11" "fixed\x11 \x12symbol\x12",
            "\x03" "33colour with two digits\x03"
        };
        ojson::Value lessArr = ojson::Value::Arr();
        for (int i = 0; i < (int)(sizeof(kLessProbes) / sizeof(kLessProbes[0])); i++) {
            fprintf(stderr, "ORACLE: codecs - szControlLess probe %d\n", i); fflush(stderr);
            char mutableIn[512];
            strncpy(mutableIn, kLessProbes[i], sizeof(mutableIn) - 1);
            mutableIn[sizeof(mutableIn) - 1] = 0;
            CDWordArray rgdw;
            char* out = SzControlLess(mutableIn, &rgdw);
            ojson::Value e = ojson::Value::Obj();
            e.Set("input", CodecStr(kLessProbes[i]));
            e.Set("output", CodecStr(out));
            e.Set("formatting", DumpFormattingArray(rgdw));
            lessArr.Push(e);
        }
        fmt.Set("szControlLess", lessArr);

        // SzControlFull: the inverse - re-inserts control codes from a
        // formatting array. ASSERTs on a NULL array, so always pass one.
        struct FullProbe { const char* text; int nRuns; DWORD runs[4]; };
        static const FullProbe kFull[] = {
            { "no formatting", 0, { 0, 0, 0, 0 } },
            { "bold from start", 1, { (DWORD)MAKELONG(wBold, 0), 0, 0, 0 } },
            { "half bold here", 2, { (DWORD)MAKELONG(wBold, 0), (DWORD)MAKELONG(0, 4), 0, 0 } },
            { "colour run", 1, { (DWORD)MAKELONG(0x0033, 0), 0, 0, 0 } },
            { "three runs total", 3, { (DWORD)MAKELONG(wBold, 0), (DWORD)MAKELONG(wItalic, 5), (DWORD)MAKELONG(0, 11), 0 } }
        };
        ojson::Value fullArr = ojson::Value::Arr();
        for (int i = 0; i < (int)(sizeof(kFull) / sizeof(kFull[0])); i++) {
            fprintf(stderr, "ORACLE: codecs - szControlFull probe %d\n", i); fflush(stderr);
            CDWordArray rgdw;
            for (int r = 0; r < kFull[i].nRuns; r++) rgdw.Add(kFull[i].runs[r]);
            char* out = SzControlFull(kFull[i].text, &rgdw);
            ojson::Value e = ojson::Value::Obj();
            e.Set("input", CodecStr(kFull[i].text));
            e.Set("formatting", DumpFormattingArray(rgdw));
            e.Set("output", CodecStr(out));
            fullArr.Push(e);
        }
        fmt.Set("szControlFull", fullArr);

        // The colour map the plan lists under #7. nFillFormatting encodes a
        // colour as ((format >> 4) & 0x0F) + 16 for the foreground and
        // (format & 0x0F) + 16 for the background, emitted as two ASCII
        // digits - so the meaningful code domain is 0..31. Round-tripped
        // through GetColorCode to show whether the mapping is injective.
        // (GetRBGColor's name transposes RGB; kept verbatim.)
        {
            ojson::Value colours = ojson::Value::Arr();
            for (int code = 0; code <= 31; code++) {
                COLORREF cr = GetRBGColor((BYTE)code);
                BYTE back = GetColorCode(cr);
                ojson::Value e = ojson::Value::Obj();
                e.Set("code", ojson::Value::Int((long)code));
                e.Set("colorref", ojson::Value::Int((long)cr));
                e.Set("r", ojson::Value::Int((long)GetRValue(cr)));
                e.Set("g", ojson::Value::Int((long)GetGValue(cr)));
                e.Set("b", ojson::Value::Int((long)GetBValue(cr)));
                e.Set("codeRoundTrip", ojson::Value::Int((long)back));
                e.Set("roundTrips", ojson::Value::Bool(back == (BYTE)code));
                colours.Push(e);
            }
            fmt.Set("colorMap", colours);
        }
        root.Set("formatting", fmt);
    }

    // --- Tier-1 #6: IRC line parse --------------------------------------
    {
        static const char* kIrcProbes[] = {
            ":nick!user@machine PRIVMSG #room :hello there",
            "PING :server.example.com",
            ":server 001 mynick :Welcome to the network",
            ":nick!user@machine JOIN #room",
            ":nick!user@machine JOIN :#room",
            "NOTICE AUTH :*** Looking up your hostname",
            // MAXARGS spill (ircsock.cpp:234 - `goto end` once nArgs hits 10,
            // dumping the remainder into lastString). The trailing part must NOT
            // begin with ':' or the whole tail collapses into lastString after
            // two args and the spill path never runs - which is what the first
            // version of this probe did.
            ":n!u@m PRIVMSG a b c d e f g h i j k l m n o p",
            ":n!u@m PRIVMSG #r :a b c d e f g h i j k l m n o p",
            ":n!u@m MODE #room +o someone",
            "",
            // NOT probed: a prefix with no following space, e.g.
            // ":only.a.prefix". ParseIt does `szBody = strchr(szMessage, ' ')`
            // then `ASSERT(szBody)` - "messages must have a body"
            // (ircsock.cpp:159) - and that assert is the only guard. In the
            // release build it compiles away and the next line computes
            // `szBody - szMessage` from a NULL, feeding garbage to strncpy.
            // That crashed this dump (0xC0000005) on its first run. The input
            // is outside the parser's stated contract, so it is left out
            // rather than pinned; the fragility is recorded in the LEDGER.
            ":n!u@m QUIT :Client exited \"with quotes\""
        };
        ojson::Value arr = ojson::Value::Arr();
        for (int i = 0; i < (int)(sizeof(kIrcProbes) / sizeof(kIrcProbes[0])); i++) {
            fprintf(stderr, "ORACLE: codecs - ircParse probe %d\n", i); fflush(stderr);
            IRCPARSE parse;
            memset(&parse, 0, sizeof(parse));
            ParseIt(kIrcProbes[i], &parse);
            ojson::Value e = ojson::Value::Obj();
            e.Set("line", CodecStr(kIrcProbes[i]));
            e.Set("bHasPrefix", ojson::Value::Bool(parse.bHasPrefix ? true : false));
            e.Set("nick", CodecStr(parse.nick));
            e.Set("user", CodecStr(parse.user));
            e.Set("machine", CodecStr(parse.machine));
            e.Set("uCode", ojson::Value::Int((long)parse.uCode));
            e.Set("nArgs", ojson::Value::Int((long)parse.nArgs));
            ojson::Value args = ojson::Value::Arr(), offs = ojson::Value::Arr();
            for (int a = 0; a < parse.nArgs && a < MAXARGS; a++) {
                args.Push(CodecStr(parse.args[a]));
                offs.Push(ojson::Value::Int((long)parse.nOffsets[a]));
            }
            e.Set("args", args);
            e.Set("nOffsets", offs);
            // lastString is where the trailing ":..." payload lands - the
            // message text itself for PRIVMSG, and everything past MAXARGS when
            // a line spills. Dumping args without it would pin the envelope and
            // drop the letter.
            e.Set("lastString", CodecStr(parse.lastString));
            e.Set("hasLastString", ojson::Value::Bool(parse.lastString ? true : false));
            arr.Push(e);
            FreeParse(&parse);
        }
        root.Set("ircParse", arr);
    }

    // --- Tier-1 #8: URL detection (live path) ---------------------------
    {
        static const char* kUrlProbes[] = {
            "no url here at all",
            "visit http://www.example.com now",
            "https://secure.example.com/path?q=1&r=2",
            "www.example.com without a scheme",
            "mic://chat.example.com/room is the Comic Chat scheme",
            "irc://irc.example.com/room too",
            "trailing punctuation http://example.com.",
            "in parens (http://example.com) here",
            "two http://a.example.com and http://b.example.com urls",
            "mailto:someone@example.com address",
            "ftp://files.example.com/pub/file.txt",
            "percent escapes http://example.com/%41%42 here"
        };
        ojson::Value arr = ojson::Value::Arr();
        for (int i = 0; i < (int)(sizeof(kUrlProbes) / sizeof(kUrlProbes[0])); i++) {
            fprintf(stderr, "ORACLE: codecs - url probe %d\n", i); fflush(stderr);
            int bounds[MAX_URL_INTEXT * 2];
            memset(bounds, 0, sizeof(bounds));
            int nUrls = MAX_URL_INTEXT;
            // HrIdentifyUrls takes LPCTSTR but writes through it: it stamps a
            // terminator over the scheme's colon to test the prefix and then
            // restores it (artifacts-modern/core/urlutil.cpp:311-313). Passing a
            // string literal therefore faults on read-only memory - which is
            // exactly how this dump crashed on its first URL probe, while the
            // no-colon probe before it survived. The buffer must be writable.
            char mutableUrl[512];
            strncpy(mutableUrl, kUrlProbes[i], sizeof(mutableUrl) - 1);
            mutableUrl[sizeof(mutableUrl) - 1] = 0;
            HRESULT hr = g_urlRec.HrIdentifyUrls(mutableUrl, bounds, &nUrls);
            ojson::Value e = ojson::Value::Obj();
            e.Set("text", CodecStr(kUrlProbes[i]));
            e.Set("hr", ojson::Value::Int((long)hr));
            e.Set("nUrlNum", ojson::Value::Int((long)nUrls));
            ojson::Value bb = ojson::Value::Arr();
            ojson::Value found = ojson::Value::Arr();
            for (int u = 0; u < nUrls && u < MAX_URL_INTEXT; u++) {
                ojson::Value pair = ojson::Value::Obj();
                pair.Set("start", ojson::Value::Int((long)bounds[u * 2]));
                pair.Set("end", ojson::Value::Int((long)bounds[u * 2 + 1]));
                bb.Push(pair);
                // The substring the bounds select, so a divergence is readable
                // without cross-referencing offsets by hand.
                int s = bounds[u * 2], e2 = bounds[u * 2 + 1];
                if (s >= 0 && e2 >= s && e2 <= (int)strlen(mutableUrl)) {
                    std::string sub(mutableUrl + s, (size_t)(e2 - s));
                    found.Push(ojson::Value::Str(sub));
                }
            }
            e.Set("bounds", bb);
            e.Set("substrings", found);
            arr.Push(e);
        }
        root.Set("urls", arr);
    }

    // --- Tier-1 #12: CDosKey ring buffer --------------------------------
    // The interesting behaviour is wraparound: append past the cap and walk
    // backwards, which exercises the modulo arithmetic over m_iStartIndex /
    // m_iEndIndex / m_iCurIndex.
    {
        fprintf(stderr, "ORACLE: codecs - doskey\n"); fflush(stderr);
        ojson::Value dk = ojson::Value::Obj();
        const UINT kMax = 4;
        CDosKey key;
        key.SetMaxSize(kMax);
        dk.Set("maxSize", ojson::Value::Int((long)kMax));

        ojson::Value appended = ojson::Value::Arr();
        static const char* kEntries[] = { "one", "two", "three", "four", "five", "six" };
        for (int i = 0; i < (int)(sizeof(kEntries) / sizeof(kEntries[0])); i++) {
            BOOL ok = key.bAppendEntry(CString(kEntries[i]), NULL);
            ojson::Value e = ojson::Value::Obj();
            e.Set("entry", ojson::Value::Str(kEntries[i]));
            e.Set("accepted", ojson::Value::Bool(ok ? true : false));
            appended.Push(e);
        }
        dk.Set("appended", appended);

        // Walk backwards past the end, then forwards again. Six appends into a
        // four-slot ring means the first two should be gone.
        key.SeekToEnd();
        ojson::Value prev = ojson::Value::Arr();
        for (int i = 0; i < 6; i++) {
            CDWordArray* fmt = NULL;
            CString s = key.StrGetPrevEntry(&fmt);
            prev.Push(CodecStr((const char*)s));
        }
        dk.Set("walkPrev", prev);

        ojson::Value next = ojson::Value::Arr();
        for (int i = 0; i < 6; i++) {
            CDWordArray* fmt = NULL;
            CString s = key.StrGetNextEntry(&fmt);
            next.Push(CodecStr((const char*)s));
        }
        dk.Set("walkNext", next);

        // And an empty ring, since ResetContent is its own path.
        key.ResetContent();
        CDWordArray* fmt = NULL;
        dk.Set("afterResetPrev", CodecStr((const char*)key.StrGetPrevEntry(&fmt)));
        root.Set("doskey", dk);
    }

    return root;
}

// ---------------------------------------------------------------------------
// Tier-1 #10: the .ccc transcript codec (histent.cpp).
//
// The plan asks for byte-exact WriteSelf goldens plus parse-then-serialize
// identity across all nine entry keywords. Rather than hand-writing .ccc lines
// (and risking pinning my transcription instead of the format), each entry is
// built with its live constructor, serialised, re-parsed through the
// CString constructor, and serialised again. Identity between the two
// serialisations is the round-trip proof, and the first serialisation is the
// byte golden.
//
// A CChatDoc is required: SayEntry's parse ctor calls LookupPui(nick, doc) and
// fabricates a CUserInfo through CIUserJoin when the nick is unknown ("got a
// say without a join -- fake it").
// ---------------------------------------------------------------------------

// Serialise one entry through a CArchive over a CMemFile. The archive must be
// closed before the file is read back or the tail sits in the archive buffer.
static std::string WriteEntryBytes(HistoryEntry* entry) {
    CMemFile mf;
    {
        CArchive ar(&mf, CArchive::store);
        entry->WriteSelf(ar);
        ar.Close();
    }
    UINT len = (UINT)mf.GetLength();
    mf.SeekToBegin();
    std::string out;
    if (len) {
        out.resize(len);
        mf.Read(&out[0], len);
    }
    return out;
}

static ojson::Value DumpBytes(const std::string& s) {
    ojson::Value v = ojson::Value::Obj();
    v.Set("text", ojson::Value::Str(s));
    v.Set("length", ojson::Value::Int((long)s.size()));
    // Hex too: the format is tab and CRLF delimited, and those are exactly the
    // bytes a diff of escaped text is easiest to misread.
    std::string hex;
    static const char* kHexDigits = "0123456789abcdef";
    for (size_t i = 0; i < s.size(); i++) {
        unsigned char c = (unsigned char)s[i];
        if (i) hex += ' ';
        hex += kHexDigits[(c >> 4) & 0x0F];
        hex += kHexDigits[c & 0x0F];
    }
    v.Set("hex", ojson::Value::Str(hex));
    return v;
}

// Serialise, re-parse via the supplied parser, serialise again, and report
// whether the two byte strings agree.
typedef HistoryEntry* (*CccParser)(CString& line, CChatDoc* doc);

static ojson::Value RoundTripEntry(const char* keyword, HistoryEntry* live,
                                   CccParser parse, CChatDoc* doc) {
    ojson::Value e = ojson::Value::Obj();
    e.Set("keyword", ojson::Value::Str(keyword));

    fprintf(stderr, "ORACLE: ccc - %s serialise\n", keyword); fflush(stderr);
    std::string first = WriteEntryBytes(live);
    e.Set("written", DumpBytes(first));

    if (!parse) {
        e.Set("reparsed", ojson::Value::Str("(no CString parser exercised)"));
        return e;
    }

    fprintf(stderr, "ORACLE: ccc - %s reparse\n", keyword); fflush(stderr);
    // Strip the record terminator before re-parsing. A .ccc reader consumes
    // whole lines and hands over the content without the CRLF; feeding it back
    // in makes the terminator part of the final field, so every entry came back
    // with a doubled CRLF and the say variants had theirs re-quoted as a
    // literal \r\n by QuoteReturns. That was the harness misreading the format,
    // not the codec failing to round-trip.
    std::string body = first;
    while (!body.empty() && (body[body.size() - 1] == '\n' || body[body.size() - 1] == '\r')) {
        body.erase(body.size() - 1);
    }
    e.Set("reparsedFrom", ojson::Value::Str(body));
    CString line(body.c_str());
    HistoryEntry* again = parse(line, doc);
    if (!again) {
        e.Set("reparseFailed", ojson::Value::Bool(true));
        return e;
    }
    std::string second = WriteEntryBytes(again);
    e.Set("rewritten", DumpBytes(second));
    e.Set("roundTrips", ojson::Value::Bool(first == second));
    delete again;
    return e;
}

// One thunk per keyword, because the parse constructors do not share a
// signature (SayEntry wants the doc, JoinEntry a highlight type, the rest just
// the line).
static HistoryEntry* ParseSay(CString& l, CChatDoc* d) { return new SayEntry(l, d, (char)-1); }
static HistoryEntry* ParseJoin(CString& l, CChatDoc*) { return new JoinEntry(l, (char)-1); }
static HistoryEntry* ParsePart(CString& l, CChatDoc*) { return new PartEntry(l); }
static HistoryEntry* ParseChangeAvatar(CString& l, CChatDoc*) { return new ChangeAvatarEntry(l); }
static HistoryEntry* ParseGetInfo(CString& l, CChatDoc*) { return new GetInfoEntry(l); }
static HistoryEntry* ParseComicCharacter(CString& l, CChatDoc*) { return new ComicCharacterEntry(l); }
static HistoryEntry* ParseStartHistory(CString& l, CChatDoc*) { return new StartHistoryEntry(l); }
static HistoryEntry* ParseChangeBackDrop(CString& l, CChatDoc*) { return new ChangeBackDropEntry(l); }
static HistoryEntry* ParseNick(CString& l, CChatDoc*) { return new NickEntry(l); }

static ojson::Value CaptureCcc(CChatDoc* doc) {
    ojson::Value root = ojson::Value::Obj();
    ojson::Value entries = ojson::Value::Arr();

    // A user info to hang the speaker-bearing entries off.
    CUserInfo* pui = new CUserInfo(CString("oraclenick"));

    // Register it in the doc's nick map so the parse constructors resolve the
    // speaker through LookupPui. Without this they fall into
    // CIUserJoin (histent.cpp:236, "got a say without a join -- fake it"),
    // which is not survivable on a bare doc: it dereferences
    // doc->m_proto->m_dwModes (protsupp.cpp:577), calls AssignArbitraryAvatar,
    // and appends to the members list - protocol and UI state a codec dump has
    // no business standing up. That crashed the first run right after "say
    // serialise". Registering the nick keeps the dump on the codec path.
    doc->m_mapNickToPtr.SetAt("oraclenick", (void*)pui);

    // say, plain
    {
        SayEntry* e = new SayEntry(pui, "hello transcript", NULL, (char)-1);
        entries.Push(RoundTripEntry("say", e, ParseSay, doc));
        delete e;
    }
    // say, with formatting - WriteSelf runs the text back through
    // SzControlFull, so this is where #7 and #10 meet.
    {
        CDWordArray* fmt = new CDWordArray;
        fmt->Add((DWORD)MAKELONG(wBold, 0));
        fmt->Add((DWORD)MAKELONG(0, 5));
        SayEntry* e = new SayEntry(pui, "bold start then plain", fmt, (char)-1);
        entries.Push(RoundTripEntry("say+formatting", e, ParseSay, doc));
        delete e;
    }
    // say, with an embedded newline: WriteSelf calls QuoteReturns, since a
    // transcript line cannot contain a raw CRLF.
    {
        SayEntry* e = new SayEntry(pui, "first line\r\nsecond line", NULL, (char)-1);
        entries.Push(RoundTripEntry("say+returns", e, ParseSay, doc));
        delete e;
    }
    {
        JoinEntry* e = new JoinEntry(pui, TRUE, (char)-1);
        entries.Push(RoundTripEntry("join", e, ParseJoin, doc));
        delete e;
    }
    {
        PartEntry* e = new PartEntry("oraclenick", (char)-1);
        entries.Push(RoundTripEntry("part", e, ParsePart, doc));
        delete e;
    }
    {
        ChangeAvatarEntry* e = new ChangeAvatarEntry(pui, "bolo", "http://example.com/bolo.avb");
        entries.Push(RoundTripEntry("changeavatar", e, ParseChangeAvatar, doc));
        delete e;
    }
    {
        GetInfoEntry* e = new GetInfoEntry(pui, (char*)"some info text");
        entries.Push(RoundTripEntry("getinfo", e, ParseGetInfo, doc));
        delete e;
    }
    {
        ComicCharacterEntry* e = new ComicCharacterEntry(pui);
        entries.Push(RoundTripEntry("comiccharacter", e, ParseComicCharacter, doc));
        delete e;
    }
    // StartHistoryEntry carries the PRNG seed. Plan section 4.3 records that
    // WriteSelf does not persist m_randStart, so a .ccc cannot reproduce a
    // comic on its own - this golden is the evidence for that claim.
    {
        StartHistoryEntry* e = new StartHistoryEntry("Oracle Comic", "bolo", 12345);
        entries.Push(RoundTripEntry("starthistory", e, ParseStartHistory, doc));
        delete e;
    }
    {
        ChangeBackDropEntry* e = new ChangeBackDropEntry("cityscape", "http://example.com/city.bgb");
        entries.Push(RoundTripEntry("changebackdrop", e, ParseChangeBackDrop, doc));
        delete e;
    }
    {
        NickEntry* e = new NickEntry("oldnick", "newnick");
        entries.Push(RoundTripEntry("nick", e, ParseNick, doc));
        delete e;
    }

    root.Set("entries", entries);
    return root;
}

